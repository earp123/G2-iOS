//
//  GoldenVectors.swift
//  G2-iOSTests
//
//  Hand-authored wire payloads for contract v3 (§7; firmware thresholds-v3 §2).
//
//  These are **golden vectors**: every byte is written out literally from the
//  byte tables in `docs/sen66-migration.md` §1 and firmware
//  `docs/thresholds-v3.md` §2, not produced by the app's own encoders. A test
//  that encoded with the same code it decodes would pass even if both sides
//  drifted from the firmware together; these cannot.
//
//  Expected decoded values are stated alongside each vector so a mismatch says
//  what the contract promised, not just that two numbers differ.
//

